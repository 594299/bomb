let aiLastReactAt = 0;
function aiReactToSkill(skillId){
    if(!G.mode.includes('ai') || G.mode==='tutorial') return;
    if(SECRET_SKILLS.has(skillId)) return; // 秘密技能对AI不可见：它不知道你用了，自然也不会吐槽（吐槽=泄密）
    const lines = AI_SKILL_REACT[skillId]; // 逐技能专属吐槽
    if(!lines) return;
    if(Date.now()-aiLastReactAt < 8000) return; // 节流：别把气泡刷成弹幕
    if(Math.random() >= 0.45) return;
    aiLastReactAt = Date.now();
    const line = lines[Math.floor(Math.random()*lines.length)];
    setTimeout(function(){ if(G.active) aiSpeak(line); }, 1000);
}

let aiTalkTimer = null;

let aiLastCat = null, aiLastLine = null; // AI 对话记忆：上一句的类别与原文

function aiSpeak(text, encourage){
    const el = $('ai-talk');
    if(!el) return;
    el.textContent = '🤖 ' + text;
    el.classList.toggle('encourage', !!encourage);
    el.classList.add('show');
    if(aiTalkTimer) clearTimeout(aiTalkTimer);
    aiTalkTimer = setTimeout(function(){ el.classList.remove('show'); }, 3500);
}

function aiTalk(category){
    if(!G.mode.includes('ai')) return;
    // 优先接上一句：有承接词库就用，保证下一句对得上上一句
    let lines = null;
    const key = aiLastCat + '->' + category;
    if(aiLastCat && AI_FOLLOWUPS[key] && AI_FOLLOWUPS[key].length && Math.random()<0.75) lines = AI_FOLLOWUPS[key];
    if(!lines) lines = AI_TALKS[category];
    if(!lines || !lines.length) return;
    // 避免连续两句一字不差
    let pool = aiLastLine ? lines.filter(l=>l!==aiLastLine) : lines;
    if(!pool.length) pool = lines;
    const line = pool[Math.floor(Math.random()*pool.length)];
    const encourage = category==='encourage' || category==='startEncourage' || (category==='aiLose' && Math.random()<0.5);
    aiSpeak(line, encourage);
    aiLastCat = category; aiLastLine = line;
}

